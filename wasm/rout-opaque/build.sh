#!/usr/bin/env bash
# Deterministic build of the ROUT OPAQUE + Argon2id engine (owner rule F.2).
#
#   wasm/rout-opaque/build.sh          build, then write the .wasm and the
#                                      embedded base64 module into src/
#   wasm/rout-opaque/build.sh --check  build in a clean target dir and fail
#                                      unless the SHA-384 equals the pin
#
# Reproducible from: rustc 1.95.0 (pinned below), Cargo.lock (--locked),
# release profile without debug info, no embedded paths. CI runs --check.
set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(cd ../.. && pwd)"
RUSTC_PIN="rustc 1.95.0"
OUT_DIR="$ROOT/src/lib/crypto-enclave/wasm"
PIN_FILE="$ROOT/src/lib/crypto-enclave/opaque-wasm-pin.ts"

actual="$(rustc --version)"
case "$actual" in
  "$RUSTC_PIN "*) ;;
  *) echo "rustc pin mismatch: want $RUSTC_PIN, have $actual" >&2; exit 2 ;;
esac

TARGET_DIR="$(mktemp -d)"
trap 'rm -rf "$TARGET_DIR"' EXIT
# Fixed, imported linear memory: the host creates WebAssembly.Memory with
# initial == maximum for every operation and zero-fills it afterwards. 32 pages
# (2 MiB) minimum for steps without key stretching, 1088 pages (68 MiB) maximum
# for the Argon2id steps. No allocator is linked, so the module contains no
# memory.grow (checked by opaque-engine.test.ts). Path remapping keeps local
# paths out of the binary even if a panic location survives.
export RUSTFLAGS="-C link-arg=--import-memory -C link-arg=--initial-memory=2097152 -C link-arg=--max-memory=71303168 -C link-arg=-zstack-size=1048576 --remap-path-prefix=${CARGO_HOME:-$HOME/.cargo}=/cargo --remap-path-prefix=$PWD=/rout-opaque"
export SOURCE_DATE_EPOCH=0
CARGO_TARGET_DIR="$TARGET_DIR" cargo build --release --locked --target wasm32-unknown-unknown
WASM="$TARGET_DIR/wasm32-unknown-unknown/release/rout_opaque.wasm"
SHA384="$(sha384sum "$WASM" | cut -d' ' -f1)"
echo "sha384 $SHA384"

if [[ "${1:-}" == "--check" ]]; then
  PINNED="$(grep -oE '[0-9a-f]{96}' "$PIN_FILE" | head -1)"
  if [[ "$SHA384" != "$PINNED" ]]; then echo "reproducible build mismatch: pinned $PINNED" >&2; exit 1; fi
  cmp "$WASM" "$OUT_DIR/rout-opaque.wasm"
  echo "reproducible: matches the pin and the committed module"
  exit 0
fi

cp "$WASM" "$OUT_DIR/rout-opaque.wasm"
{
  echo "// Generated by wasm/rout-opaque/build.sh — do not edit. SHA-384 pinned in opaque-wasm-pin.ts."
  printf 'export const ROUT_OPAQUE_WASM_BASE64 =\n  "%s";\n' "$(base64 -w0 "$WASM")"
} > "$OUT_DIR/rout-opaque.wasm.base64.ts"
echo "wrote $OUT_DIR/rout-opaque.wasm (update opaque-wasm-pin.ts if the hash changed)"
